#!/usr/bin/env python3
"""Generate src/module_pins.{c,h} from GOcontroll-Architecture/modules/pinning.md.

Only the MDS1 / MDS2 columns are kept — this demo targets the Moduline HMI1
which has two slots. Run with the path to pinning.md as the first argument;
without it, falls back to fetching the latest from GitHub via a token in the
environment variable GITHUB_TOKEN.
"""
import argparse
import os
import re
import sys
import urllib.request

REPO_PATH = 'repos/GOcontroll/GOcontroll-Architecture/contents/modules/pinning.md'


def fetch_from_github():
    tok = os.environ.get('GITHUB_TOKEN')
    if not tok:
        sys.exit('GITHUB_TOKEN env var required when pinning.md path is not given')
    req = urllib.request.Request(
        f'https://api.github.com/{REPO_PATH}',
        headers={'Authorization': f'token {tok}',
                 'Accept': 'application/vnd.github.raw'})
    with urllib.request.urlopen(req, timeout=15) as r:
        return r.read().decode('utf-8')


def parse(text):
    """Yield (name, article_number, [(func, desc, mds1, mds2), ...]) per module."""
    sections = re.split(r'^### ', text, flags=re.MULTILINE)
    # [0] = preamble, [1..3] = controller overviews, [4:] = module definitions
    for sec in sections[4:]:
        name_line, rest = sec.split('\n', 1)
        name = name_line.strip()
        art_m = re.search(r'\*\*Artikelnummer:\*\*\s*(\S+)', rest)
        article = art_m.group(1) if art_m else '-'
        rows = []
        for line in rest.splitlines():
            if not line.startswith('|'):
                continue
            cells = [c.strip() for c in line.strip().strip('|').split('|')]
            if len(cells) < 16:
                continue
            if cells[0] in ('Functie', 'Omschrijving') or cells[0].startswith(':-'):
                continue
            if all(c == '' or set(c) <= set(':-') for c in cells):
                continue
            # Columns in the upstream table:
            # 0=Functie 1=Omschrijving 2..9=M4S1..M4S8 10..13=MMS1..MMS4 14=MDS1 15=MDS2
            rows.append((cells[0], cells[1], cells[14], cells[15]))
        yield name, article, rows


HEADER_H = '''#ifndef GOCONTROLL_HMI_MODULE_PINS_H
#define GOCONTROLL_HMI_MODULE_PINS_H

#include <stddef.h>

/* Pin table for one module type on the Moduline HMI1 controller only.
 * Columns: function, description, MDS1 pin, MDS2 pin. All strings are
 * static string literals so no allocation or cleanup is needed. */
typedef struct {
    const char *function;
    const char *description;
    const char *mds1;
    const char *mds2;
} module_pin_t;

typedef struct {
    const char        *name;
    const char        *article_number;
    const module_pin_t *pins;
    size_t             pin_count;
} module_def_t;

extern const module_def_t g_module_defs[];
extern const size_t       g_module_def_count;

#endif
'''


def emit(modules, out_c, out_h):
    with open(out_h, 'w') as f:
        f.write(HEADER_H)

    def esc(s):
        return s.replace('\\', '\\\\').replace('"', r'\"')

    with open(out_c, 'w') as f:
        f.write('/* AUTO-GENERATED by scripts/gen_module_pins.py from\n')
        f.write(' * GOcontroll-Architecture/modules/pinning.md. Only the HMI1 slots\n')
        f.write(' * (MDS1/MDS2) are kept. Do not edit by hand. */\n')
        f.write('#include "module_pins.h"\n\n')
        ids = []
        for i, (name, article, rows) in enumerate(modules):
            ident = f'pins_{i:02d}'
            ids.append((ident, name, article, len(rows)))
            f.write(f'/* {name}  (article {article}) */\n')
            f.write(f'static const module_pin_t {ident}[] = {{\n')
            for fn, desc, m1, m2 in rows:
                f.write(f'    {{ "{esc(fn)}", "{esc(desc)}", '
                        f'"{esc(m1)}", "{esc(m2)}" }},\n')
            f.write('};\n\n')

        f.write('const module_def_t g_module_defs[] = {\n')
        for ident, name, article, n in ids:
            f.write(f'    {{ "{esc(name)}", "{esc(article)}", {ident}, {n} }},\n')
        f.write('};\n\n')
        f.write('const size_t g_module_def_count = sizeof(g_module_defs) /'
                ' sizeof(g_module_defs[0]);\n')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('pinning_md', nargs='?',
                    help='Path to pinning.md. If omitted, fetches from GitHub.')
    ap.add_argument('--out-dir', default='src',
                    help='Directory to write module_pins.{c,h} into')
    args = ap.parse_args()

    text = open(args.pinning_md).read() if args.pinning_md else fetch_from_github()
    mods = list(parse(text))
    emit(mods,
         os.path.join(args.out_dir, 'module_pins.c'),
         os.path.join(args.out_dir, 'module_pins.h'))
    print(f'emitted {len(mods)} module definitions')
    for name, art, rows in mods:
        print(f'  - {name}  (article {art})  {len(rows)} rows')


if __name__ == '__main__':
    main()
